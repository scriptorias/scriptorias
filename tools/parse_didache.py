"""Parse the Lightfoot Didache from Wikisource wikitext into data/didache.js.

Source: https://en.wikisource.org/wiki/Didache_(Lightfoot_translation) (public domain, 1891).
Segment numbers follow Wikisource's segmentation, not a standard verse system; they are
marked provisional in the output until a reference scheme is chosen.
"""
import json, re, sys

SAMPLE_CHAPTERS = [1, 2, 3]
raw = open(sys.argv[1], encoding="utf-8").read()
seg_re = re.compile(r"<section begin=(\d+):(\d+)/>(.*?)<section end=\1:\2/>", re.S)

chapters, em_open = {}, False
for ch, n, body in seg_re.findall(raw):
    ch, n = int(ch), int(n)
    runs, pos = [], 0
    for m in re.finditer(r"</?em>", body):
        if m.start() > pos:
            runs.append({"t": body[pos:m.start()], **({"em": True} if em_open else {})})
        em_open = m.group() == "<em>"
        pos = m.end()
    if pos < len(body):
        runs.append({"t": body[pos:], **({"em": True} if em_open else {})})
    chapters.setdefault(ch, []).append({"ref": f"didache.{ch}.{n}", "n": str(n), "runs": runs})

sections = [{"n": c, "passages": chapters[c]} for c in SAMPLE_CHAPTERS]
data = {
    "label": "J. B. Lightfoot",
    "detail": "The Apostolic Fathers (1891)",
    "language": "English",
    "license": "Public domain",
    "source": {"label": "Wikisource: Didache (Lightfoot translation)", "href": "https://en.wikisource.org/wiki/Didache_(Lightfoot_translation)"},
    "sample": True,
    "refScheme": "provisional",
    "italics": "Italic type follows Lightfoot, who set quotations of Scripture in italics.",
    "sections": sections,
}
out = (
    "window.TEXTS = window.TEXTS || {};\n"
    "// Generated by tools/parse_didache.py. Sample: chapters 1–3 only.\n"
    "window.TEXTS.didache = {\n"
    "  work: \"didache\",\n"
    "  sectionLabel: \"Chapter\",\n"
    "  totalSections: %d,\n"
    "  default: \"lightfoot\",\n"
    "  translations: { lightfoot: %s },\n"
    "};\n" % (max(chapters), json.dumps(data, ensure_ascii=False, indent=1))
)
open("data/didache.js", "w", encoding="utf-8").write(out)
print({c: len(chapters[c]) for c in sorted(chapters)})
